"""Export one experiment's report tables as JSON files ({rows, meta}) for the results dashboard.

    python scripts/export_dashboard.py --experiment main-v1 --out data/dashboard

Each file holds the rows of one query from webapp/queries.py (or below) and, in meta,
the SQL that produced them, so every number on the dashboard can be traced to a query.
"""
import argparse
import json
import sys
from decimal import Decimal
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from t2s import costs, db  # noqa: E402
from webapp import queries as Q  # noqa: E402

REPEATS = """
SELECT c.label, r.repeat_no, count(*) AS runs, round(100.0 * avg(v.is_correct::int), 1) AS ex_percent,
       round(100.0 * avg(v.reward), 2) AS rves
FROM v_run_rves v JOIN run r ON r.run_id = v.run_id JOIN pipeline_config c ON c.config_id = v.config_id
WHERE v.experiment_id = %(experiment_id)s GROUP BY 1, 2 ORDER BY 1, 2"""

DIFFICULTY = """
SELECT q.difficulty, c.label, count(*) AS runs, round(100.0 * avg(v.is_correct::int), 1) AS ex_percent,
       round(100.0 * avg(v.reward), 2) AS rves
FROM v_run_rves v JOIN question q ON q.question_id = v.question_id JOIN pipeline_config c ON c.config_id = v.config_id
WHERE v.experiment_id = %(experiment_id)s GROUP BY 1, 2
ORDER BY array_position(ARRAY['simple','moderate','challenging'], q.difficulty::text), 2"""

TOKENS = """
SELECT c.label, c.model_name, count(DISTINCT r.run_id) AS runs, count(*) AS llm_calls,
       sum(l.input_tokens) AS input_tokens, sum(l.output_tokens) AS output_tokens
FROM llm_call l JOIN run r ON r.run_id = l.run_id JOIN pipeline_config c ON c.config_id = r.config_id
WHERE r.experiment_id = %(experiment_id)s GROUP BY 1, 2 ORDER BY 1"""

SPEEDUPS = """
SELECT o.run_id, r.question_id, d.db_name, q.question_text, c.label,
       round((o.base_median_ms / NULLIF(o.median_ms, 0))::numeric, 2) AS speedup,
       round(o.base_median_ms::numeric, 2) AS before_ms, round(o.median_ms::numeric, 2) AS after_ms,
       o.matches_gold, b.sql_text AS before_sql, g.sql_text AS after_sql,
       (SELECT string_agg(issue, ', ') FROM plan_issue pi WHERE pi.run_id = o.run_id AND pi.step_no = o.base_step_no) AS issues_before
FROM v_rewrite_outcome o
JOIN run r ON r.run_id = o.run_id
JOIN question q ON q.question_id = r.question_id
JOIN target_database d ON d.db_id = q.db_id
JOIN pipeline_config c ON c.config_id = r.config_id
JOIN generated_query g ON g.run_id = o.run_id AND g.step_no = o.step_no
JOIN generated_query b ON b.run_id = o.run_id AND b.step_no = o.base_step_no
WHERE o.experiment_id = %(experiment_id)s AND o.accepted
ORDER BY speedup DESC NULLS LAST LIMIT 8"""


def plain(v):
    if isinstance(v, Decimal):
        return float(v)
    return v


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--experiment", required=True)
    ap.add_argument("--out", default="data/dashboard")
    a = ap.parse_args()
    out = Path(a.out)
    out.mkdir(parents=True, exist_ok=True)

    conn = db.connect()
    e = db.query_one(conn, "SELECT experiment_id, name, description FROM experiment WHERE name = %s", (a.experiment,))
    p = {"experiment_id": e["experiment_id"], "slow_ms": Q.SLOW_QUESTION_MS}
    sets = {
        "summary": Q.REPORT_SUMMARY, "slowfast": Q.REPORT_SLOW_FAST, "repeats": REPEATS,
        "difficulty": DIFFICULTY, "bydb": Q.REPORT_BY_DB, "effect": Q.REPORT_REWRITE_EFFECT,
        "outcomes": Q.REPORT_REWRITES, "issues": Q.REPORT_ISSUES, "h2h": Q.REPORT_HEAD_TO_HEAD,
        "tokens": TOKENS, "speedups": SPEEDUPS,
    }
    for name, sql in sets.items():
        rows = [{k: plain(v) for k, v in r.items()} for r in db.query(conn, sql, p)]
        if name == "tokens":
            for r in rows:   # cap accounting price: input at 1.25x (errs high)
                r["est_cost_usd"] = round(costs.call_cost(r["model_name"], r["input_tokens"], r["output_tokens"]), 4)
        meta = [{"label": "Experiment", "value": f"{e['name']}: {e['description']}"},
                {"label": "Query", "value": sql.strip(), "type": "code", "lang": "sql"},
                {"label": "Generated by", "value": "scripts/export_dashboard.py from the t2s results database"}]
        (out / f"{name}.json").write_text(json.dumps({"rows": rows, "meta": meta}, indent=1, default=str))
        print(f"{name}: {len(rows)} rows")


if __name__ == "__main__":
    main()
